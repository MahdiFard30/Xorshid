"""Evidence-based additions within the installed executor's position/risk caps.

Confidence is corroboration, not a calibrated probability of making a profit.
Only additional entries are assessed; exits and existing positions are untouched.
"""
from ultimate_khorshid.tools.exit_rules import finite

FAMILIES = {
    'sma_cross':'trend','ema_cross':'trend','macd':'trend','trend_pullback':'trend',
    'roc':'momentum','donchian':'momentum',
    'rsi_rebound':'oscillator','bollinger_reentry':'oscillator','stochastic':'oscillator','cci':'oscillator',
}


def assess(snapshot, candidate, quality, opportunity):
    positions=snapshot.get('positions',[])
    limit=snapshot.get('max_positions',1)
    base={'version':1,'existing_positions':len(positions),'executor_limit':limit,
          'allow_entry':False,'evidence':[],'risk_cap_increased':False}
    if type(limit) is not int or limit not in (1,2):
        return {**base,'reason':'Unsupported executor capacity'}
    if len(positions)>=limit:
        return {**base,'reason':'Executor position limit reached'}
    direction=candidate.get('direction')
    if type(direction) is not int or direction not in (-1,1):
        return {**base,'reason':'A fresh directional entry signal is required'}
    if not positions:
        return {**base,'allow_entry':True,'reason':'First position uses normal signal and risk checks'}
    # Never average down. Require a favorable move and positive floating P/L
    # in every existing position before adding exposure on this symbol.
    if any(p.get('direction')!=direction or not finite(p.get('progress_r')) or p['progress_r']<.1
           or not finite(p.get('profit')) or p['profit']<=0 for p in positions):
        return {**base,'reason':'Additional entry waits for all existing positions to be profitable by at least 0.1R'}
    bars=snapshot.get('bars',[])
    context=candidate.get('market_context',{})
    current=bool(bars) and context.get('signal_bar')==bars[-1]['time']
    evidence=[]
    if (current and context.get('trend')==('up' if direction==1 else 'down')
            and finite(context.get('efficiency')) and context['efficiency']>=.35):
        evidence.append('Current completed-candle trend agrees')
    signals=candidate.get('signals',{})
    agreeing={FAMILIES[name] for name,value in signals.items() if name in FAMILIES and type(value) is int and value==direction}
    opposing=any(type(value) is int and value==-direction for name,value in signals.items() if name in FAMILIES)
    if (candidate.get('signal_bar')==(bars[-1]['time'] if bars else None)
            and len(agreeing)>=2 and not opposing):
        evidence.append('At least two indicator families agree without an opposing signal')
    if (quality.get('verified_samples',0)>=20 and finite(quality.get('lower_mean_r_heuristic'))
            and quality['lower_mean_r_heuristic']>0):
        evidence.append('Positive conservative estimate from verified current-policy outcomes')
    if opportunity.get('mode')=='staged':
        evidence.append('Fresh numerical release corroborated by completed price reaction')
    # This is generated by the bounded source/expiry validator, not model confidence.
    if candidate.get('headline_adjustment')==.15 and candidate.get('headline_has_article') is True:
        evidence.append('Fresh cited article analysis agrees with the technical entry signal')
    return {**base,'allow_entry':bool(evidence),'evidence':evidence,
            'reason':'Profitable position and corroborated new signal permit an additional position' if evidence
                     else 'Additional entry waits for corroborating trend, news, indicators or verified results'}
